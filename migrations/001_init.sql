-- 001_init.sql: PostgreSQL schema for Polyglot Webhook Processing Engine

CREATE EXTENSION IF NOT EXISTS "uuid-ossp";

-- 1. Tenants Table: Stores tenant configuration, credentials, rate limits, and target endpoints
CREATE TABLE IF NOT EXISTS tenants (
    id UUID PRIMARY KEY DEFAULT uuid_generate_v4(),
    name VARCHAR(255) NOT NULL,
    inbound_secret VARCHAR(255) NOT NULL,    -- Used by Go gateway to verify incoming HMAC-SHA256
    outbound_secret VARCHAR(255) NOT NULL,   -- Used by Python worker to sign outbound webhooks
    destination_url TEXT NOT NULL,           -- Target endpoint to deliver events
    rate_limit_per_second INT NOT NULL DEFAULT 50, -- Token bucket capacity/refill rate
    burst_limit INT NOT NULL DEFAULT 100,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    updated_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 2. Webhook Events Table: Primary ledger of all accepted webhook events
CREATE TABLE IF NOT EXISTS webhook_events (
    id UUID PRIMARY KEY,                     -- Generated by Go gateway
    tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    idempotency_key VARCHAR(255),            -- Optional key from client header (X-Idempotency-Key)
    event_type VARCHAR(100) NOT NULL DEFAULT 'webhook.event',
    payload JSONB NOT NULL,
    status VARCHAR(50) NOT NULL DEFAULT 'PENDING', -- PENDING, PROCESSING, DELIVERED, RETRYING, FAILED_DLQ
    max_retries INT NOT NULL DEFAULT 5,
    retry_count INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW(),
    delivered_at TIMESTAMP WITH TIME ZONE,
    failed_at TIMESTAMP WITH TIME ZONE,
    CONSTRAINT uq_tenant_idempotency UNIQUE (tenant_id, idempotency_key)
);

-- 3. Delivery Attempts Table: Granular audit trail for each HTTP delivery attempt
CREATE TABLE IF NOT EXISTS delivery_attempts (
    id BIGSERIAL PRIMARY KEY,
    event_id UUID NOT NULL REFERENCES webhook_events(id) ON DELETE CASCADE,
    attempt_number INT NOT NULL,
    destination_url TEXT NOT NULL,
    request_headers JSONB,
    status_code INT,
    response_body TEXT,
    error_message TEXT,
    latency_ms INT,
    attempted_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- 4. Dead Letter Queue Table: Persistent store for manual inspection and replay
CREATE TABLE IF NOT EXISTS dead_letter_events (
    id BIGSERIAL PRIMARY KEY,
    event_id UUID NOT NULL UNIQUE REFERENCES webhook_events(id) ON DELETE CASCADE,
    tenant_id UUID NOT NULL REFERENCES tenants(id) ON DELETE CASCADE,
    failure_reason TEXT NOT NULL,
    total_attempts INT NOT NULL,
    last_error TEXT,
    replayed_at TIMESTAMP WITH TIME ZONE,
    created_at TIMESTAMP WITH TIME ZONE DEFAULT NOW()
);

-- Indexes for high-throughput queries and status lookups
CREATE INDEX IF NOT EXISTS idx_events_tenant_status ON webhook_events(tenant_id, status);
CREATE INDEX IF NOT EXISTS idx_events_created_at ON webhook_events(created_at DESC);
CREATE INDEX IF NOT EXISTS idx_attempts_event_id ON delivery_attempts(event_id);
CREATE INDEX IF NOT EXISTS idx_dlq_tenant ON dead_letter_events(tenant_id, replayed_at);

